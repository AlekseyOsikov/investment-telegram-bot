"""Подключение бота к MCP-серверу (Model Context Protocol).

Пакет называется `mcp_integration`, а НЕ `mcp` — важное отличие от того, как обычно
называют такие пакеты. Бот запускается как `python src/main.py`, поэтому `src/`
оказывается корнем импорта: пакет `src/mcp/` затенил бы собой сам MCP SDK (пакет
`mcp` из `requirements.txt`), и `import mcp` внутри проекта резолвился бы в
локальный пустой пакет вместо SDK. Имя `mcp_integration` однозначно и не
конфликтует.

Слой не знает ни про Telegram, ни про LLM-провайдеров — по тому же принципу
разделения, что `providers/` и `agents/agent.py` отдельно от своих команд бота:
- `client.py` — подключение к серверу (stdio-транспорт, официальный SDK) и
  получение списка инструментов, а также чистое форматирование результата в текст.
- `tools_command.py` — команда бота `/mcp_tools`, переводящая результат/ошибки
  этого слоя в сообщения Telegram на русском.

Про архитектурные решения (почему одно соединение на запрос, почему тайм-аут
общий на весь цикл, почему конфигурация в config.py, а не здесь) см. design.md
изменения add-mcp-tools-listing (openspec/changes/) и «Архитектура» в CLAUDE.md.
"""

