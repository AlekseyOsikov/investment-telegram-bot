def _validate_config() -> None:
    """Проверяет наличие обязательных переменных окружения перед стартом.

    Обязательность DEEPSEEK_API_KEY/KIMI_API_KEY зависит от MAIN_CLIENT и проверяется
    отдельно в providers/deepseek_client.py/providers/kimi_client.py (модуль выбранного провайдера сам
    завершает процесс, если его ключа нет) — здесь только TELEGRAM_BOT_TOKEN и сам
    MAIN_CLIENT, т.к. это переменные, за которые отвечает именно этот модуль.
    """
    if not TELEGRAM_BOT_TOKEN:
        logger.error(
            "Отсутствует обязательная переменная окружения TELEGRAM_BOT_TOKEN. "
            "Скопируйте .env.example в .env и заполните значение."
        )
        sys.exit(1)

    if _RESEARCH_RAW not in _TRUE_VALUES | _FALSE_VALUES:
        logger.error(
            "Недопустимое значение RESEARCH=%r. Допустимые значения: true/false "
            "(также принимаются 1/0, yes/no, on/off).",
            _RESEARCH_RAW,
        )
        sys.exit(1)

    if MAIN_CLIENT not in _SUPPORTED_MAIN_CLIENTS:
        logger.error(
            "Недопустимое значение MAIN_CLIENT=%r. Допустимые значения: %s.",
            MAIN_CLIENT,
            ", ".join(_SUPPORTED_MAIN_CLIENTS),
        )
        sys.exit(1)

    if AGENT_CONTEXT_STRATEGY not in _SUPPORTED_AGENT_STRATEGIES:
        logger.error(
            "Недопустимое значение AGENT_CONTEXT_STRATEGY=%r. Допустимые значения: %s.",
            AGENT_CONTEXT_STRATEGY,
            ", ".join(_SUPPORTED_AGENT_STRATEGIES),
        )
        sys.exit(1)

    invalid_enabled_strategies = [
        name for name in AGENT_ENABLED_STRATEGIES if name not in _SUPPORTED_AGENT_STRATEGIES
    ]
    if not AGENT_ENABLED_STRATEGIES or invalid_enabled_strategies:
        logger.error(
            "Недопустимое значение AGENT_ENABLED_STRATEGIES=%r. Список не может быть "
            "пустым, каждое значение — одно из: %s.",
            ", ".join(AGENT_ENABLED_STRATEGIES),
            ", ".join(_SUPPORTED_AGENT_STRATEGIES),
        )
        sys.exit(1)

    if AGENT_CONTEXT_STRATEGY not in AGENT_ENABLED_STRATEGIES:
        logger.error(
            "AGENT_CONTEXT_STRATEGY=%r должна входить в AGENT_ENABLED_STRATEGIES=%r — "
            "иначе новые чаты стартуют со стратегией, которую сами не смогут выбрать "
            "через /agent_context.",
            AGENT_CONTEXT_STRATEGY,
            ", ".join(AGENT_ENABLED_STRATEGIES),
        )
        sys.exit(1)

    if MCP_MAX_TOOL_STEPS < 1:
        logger.error(
            "Недопустимое значение MCP_MAX_TOOL_STEPS=%r: нужно целое число не меньше 1.",
            MCP_MAX_TOOL_STEPS,
        )
        sys.exit(1)

    if MCP_TOOL_RESULT_MAX_CHARS < 1:
        logger.error(
            "Недопустимое значение MCP_TOOL_RESULT_MAX_CHARS=%r: нужно целое число "
            "не меньше 1.",
            MCP_TOOL_RESULT_MAX_CHARS,
        )
        sys.exit(1)

