"""Факты для эксперимента «добавляет ли тюн знания».

Один источник правды для датасета, eval-набора и baseline «факты в промпте».
Два вида фактов:

- ``synthetic`` — вымышленные «посаженные» факты о вымышленной компании
  «ЗаряПром» (тикер ZRPR), индикаторе «индекс Вепрецова» и фонде «Стабильный
  берег». Уникальные термины гарантируют, что базовая модель их не знает
  (нулевая утечка из предобучения), и позволяют точную автоматическую проверку
  по ``keys``.
- ``real`` — реальные факты 2026 года из корпуса ``data/source`` (после даты
  знаний Qwen2.5-1.5B), для связки с RAG. Поле ``source`` — префикс заголовка
  документа индекса, как в ``data/rag_eval/questions.json``.

Схема одного факта:

- ``id`` — уникальный идентификатор;
- ``kind`` — ``synthetic`` | ``real``;
- ``source`` — префикс заголовка документа индекса (только для ``real``);
- ``fact`` — одно предложение-знание; его подставляют в промпт в baseline
  «факты в промпте» (это ровно то, что на проде делает RAG — достаёт и вставляет
  релевантный фрагмент);
- ``judge_facts`` — пронумерованный чек-лист ожидаемых фактов для judge-оценки;
- ``keys`` — подстроки, которые ДОЛЖНЫ присутствовать в ответе (детерминированная
  проверка; используется как перекрёстный замер к judge);
- ``train`` — обучающие формулировки «вопрос → ответ» (2 на факт);
- ``valid`` — перефразированная формулировка для контроля лосса на valid;
- ``paraphrases`` — ещё одна перефразировка для eval-проверки обобщения
  (в train/valid не входит).
"""

