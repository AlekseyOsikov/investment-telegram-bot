def all_train() -> list[dict[str, str]]:
    """Все обучающие пары «вопрос → ответ»."""
    return [qa for fact in FACTS for qa in fact["train"]]


def all_valid() -> list[dict[str, str]]:
    """Все valid-пары (перефразировки для контроля лосса)."""
    return [qa for fact in FACTS for qa in fact["valid"]]


def to_messages(qa: dict[str, str]) -> list[dict[str, str]]:
    """Пара «вопрос → ответ» в формат ``messages`` (system + user + assistant)."""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": qa["q"]},
        {"role": "assistant", "content": qa["a"]},
    ]


def eval_items() -> list[dict[str, Any]]:
    """Eval-набор: по две записи на факт — обучающая формулировка (memorization)
    и перефразировка (generalization). Содержит контекст для baseline «факты
    в промпте», чек-лист для judge и ключи для детерминированной проверки."""
    items: list[dict[str, Any]] = []
    for fact in FACTS:
        for mode, qa in (("train_like", fact["train"][0]), ("paraphrase", fact["paraphrases"][0])):
            items.append(
                {
                    "id": fact["id"],
                    "kind": fact["kind"],
                    "source": fact["source"],
                    "mode": mode,
                    "question": qa["q"],
                    "answer": qa["a"],
                    "fact": fact["fact"],
                    "judge_facts": fact["judge_facts"],
                    "keys": fact["keys"],
                }
            )
    return items
